import { ProjectData, Track, StepNote, MasterFXSettings } from '../types';

function stepsFromPattern(
  pattern: string,
  pitch: string = 'C3',
  velocity: number = 0.85
): StepNote[] {
  const steps: StepNote[] = [];
  for (let i = 0; i < pattern.length; i++) {
    const char = pattern[i];
    steps.push({
      active: char.toLowerCase() === 'x',
      pitch,
      velocity: char === 'X' ? 1.0 : velocity,
    });
  }
  return steps;
}

